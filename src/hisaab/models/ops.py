"""Operational tables, transcribed from tech-design §3.4."""

from typing import Any

from sqlalchemy import ForeignKey, Index
from sqlalchemy.orm import Mapped, mapped_column

from hisaab.models.base import Base, created_column, id_column, one_of

JOB_KINDS: tuple[str, ...] = ("sync", "resync", "sweep", "statement_merge", "reprocess_normalization")
JOB_STATES: tuple[str, ...] = ("queued", "running", "succeeded", "failed", "cancelled")


class Job(Base):
    __tablename__: str = "jobs"
    __table_args__: tuple[Any, ...] = (
        one_of("kind", JOB_KINDS, "kind"),
        one_of("state", JOB_STATES, "state"),
    )

    id: Mapped[str] = id_column()
    kind: Mapped[str]
    user_id: Mapped[str | None] = mapped_column(ForeignKey("users.id"))  # NULL for instance-wide jobs
    state: Mapped[str]
    params: Mapped[str | None]  # JSON
    progress: Mapped[str | None]  # JSON
    result: Mapped[str | None]  # JSON
    error: Mapped[str | None]  # JSON
    created_at: Mapped[str] = created_column()
    started_at: Mapped[str | None]
    finished_at: Mapped[str | None]


Index("ix_jobs_user_state", Job.user_id, Job.state, Job.created_at.desc())


class UserSession(Base):
    """A login session. Named UserSession to avoid confusion with sqlalchemy.orm.Session."""

    __tablename__: str = "sessions"

    id: Mapped[str] = mapped_column(primary_key=True)  # opaque token, generated by auth (slice 3)
    user_id: Mapped[str] = mapped_column(ForeignKey("users.id"))
    created_at: Mapped[str] = created_column()
    last_seen_at: Mapped[str]  # sliding 30-day expiry


class Setting(Base):
    """Tunables (PRD §10.1). App-level rows have user_id = '' (not NULL, so the PK works)."""

    __tablename__: str = "settings"

    key: Mapped[str] = mapped_column(primary_key=True)
    user_id: Mapped[str] = mapped_column(primary_key=True, server_default="")
    value: Mapped[str]  # JSON
    updated_at: Mapped[str]
